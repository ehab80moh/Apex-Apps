
  CREATE OR REPLACE EDITIONABLE FUNCTION "EPROMHQ"."GET_MANAGER"
(p_emp_id in NUMBER)
return NUMBER
is
V_DEPARTMENT NUMBER;
V_MANAGER NUMBER;
begin
SELECT  DEPARTMENT_ID into V_DEPARTMENT from
REQ_EMPLOYEE ,REQ_USERS
where REQ_EMPLOYEE.ID = REQ_USERS.EMP_ID and REQ_USERS.EMP_ID = p_emp_id;
SELECT MANAGER_ID  into V_MANAGER FROM REQ_DEPARTMENT
where DEPARTMENT_ID = V_DEPARTMENT;
return V_MANAGER;
end;
/
