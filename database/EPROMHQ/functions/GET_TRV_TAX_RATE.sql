
  CREATE OR REPLACE EDITIONABLE FUNCTION "EPROMHQ"."GET_TRV_TAX_RATE"
RETURN NUMBER
IS
  l_val VARCHAR2(100);
BEGIN
  SELECT setting_val INTO l_val
  FROM   EPROMHQ.TRV_SETTINGS
  WHERE  setting_key = 'TAX_RATE';

  RETURN TO_NUMBER(l_val);
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RETURN 0.25; -- default fallback
END;
/
