
  CREATE OR REPLACE EDITIONABLE PACKAGE BODY "EPROMHQ"."PRC_APPROVAL_PKG" AS
    C_APPLICATION_ID CONSTANT NUMBER := 212;
    C_WORKFLOW_STATIC_ID CONSTANT VARCHAR2(30) := 'PRC_APPROVAL_WORKFLOW';
    C_WAIT_ACTIVITY_STATIC_ID CONSTANT VARCHAR2(30) := 'WAIT_FOR_VOTES';
    C_TASK_DEFINITION_STATIC_ID CONSTANT VARCHAR2(30) := 'PRC_COMMITTEE_VOTE';

    PROCEDURE FIND_ROUTE (
        P_SOURCE_APP_ID      IN NUMBER,
        P_SOURCE_ENTITY_CODE IN VARCHAR2,
        P_SOURCE_TYPE_ID     IN NUMBER,
        P_ROUTING_ID         OUT NUMBER,
        P_VERSION_ID         OUT NUMBER,
        P_DECISION_RULE      OUT VARCHAR2,
        P_REQUIRED_APPROVALS OUT NUMBER,
        P_LEGACY_FLOW_MODE   OUT VARCHAR2
    ) IS
    BEGIN
        SELECT R.ROUTING_ID,
               R.VERSION_ID,
               V.DECISION_RULE,
               V.REQUIRED_APPROVALS,
               R.LEGACY_FLOW_MODE
          INTO P_ROUTING_ID,
               P_VERSION_ID,
               P_DECISION_RULE,
               P_REQUIRED_APPROVALS,
               P_LEGACY_FLOW_MODE
          FROM PRC_COMMITTEE_ROUTING R
          JOIN PRC_COMMITTEE_VERSIONS V
            ON V.VERSION_ID = R.VERSION_ID
         WHERE R.SOURCE_APP_ID = P_SOURCE_APP_ID
           AND R.SOURCE_ENTITY_CODE = UPPER(TRIM(P_SOURCE_ENTITY_CODE))
           AND R.SOURCE_TYPE_ID = P_SOURCE_TYPE_ID
           AND R.IS_ACTIVE = 'Y'
           AND V.VERSION_STATUS = 'ACTIVE'
           AND (R.EFFECTIVE_FROM IS NULL OR R.EFFECTIVE_FROM < TRUNC(SYSDATE) + 1)
           AND (R.EFFECTIVE_TO IS NULL OR R.EFFECTIVE_TO >= TRUNC(SYSDATE))
           AND (V.EFFECTIVE_FROM IS NULL OR V.EFFECTIVE_FROM < TRUNC(SYSDATE) + 1)
           AND (V.EFFECTIVE_TO IS NULL OR V.EFFECTIVE_TO >= TRUNC(SYSDATE));
    END FIND_ROUTE;

    FUNCTION IS_ROUTED (
        P_SOURCE_APP_ID      IN NUMBER,
        P_SOURCE_ENTITY_CODE IN VARCHAR2,
        P_SOURCE_TYPE_ID     IN NUMBER
    ) RETURN BOOLEAN IS
        L_ROUTING_ID         NUMBER;
        L_VERSION_ID         NUMBER;
        L_DECISION_RULE      VARCHAR2(30);
        L_REQUIRED_APPROVALS NUMBER;
        L_LEGACY_FLOW_MODE   VARCHAR2(20);
    BEGIN
        FIND_ROUTE(P_SOURCE_APP_ID, P_SOURCE_ENTITY_CODE, P_SOURCE_TYPE_ID,
                   L_ROUTING_ID, L_VERSION_ID, L_DECISION_RULE,
                   L_REQUIRED_APPROVALS, L_LEGACY_FLOW_MODE);
        RETURN TRUE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN FALSE;
    END IS_ROUTED;

    FUNCTION SHOULD_START_LEGACY (
        P_SOURCE_APP_ID      IN NUMBER,
        P_SOURCE_ENTITY_CODE IN VARCHAR2,
        P_SOURCE_TYPE_ID     IN NUMBER
    ) RETURN BOOLEAN IS
        L_ROUTING_ID         NUMBER;
        L_VERSION_ID         NUMBER;
        L_DECISION_RULE      VARCHAR2(30);
        L_REQUIRED_APPROVALS NUMBER;
        L_LEGACY_FLOW_MODE   VARCHAR2(20);
    BEGIN
        FIND_ROUTE(P_SOURCE_APP_ID, P_SOURCE_ENTITY_CODE, P_SOURCE_TYPE_ID,
                   L_ROUTING_ID, L_VERSION_ID, L_DECISION_RULE,
                   L_REQUIRED_APPROVALS, L_LEGACY_FLOW_MODE);
        RETURN L_LEGACY_FLOW_MODE = 'PARALLEL';
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN TRUE;
    END SHOULD_START_LEGACY;

    PROCEDURE SUBMIT_REQUEST (
        P_SOURCE_APP_ID      IN NUMBER,
        P_SOURCE_ENTITY_CODE IN VARCHAR2,
        P_SOURCE_TYPE_ID     IN NUMBER,
        P_SOURCE_KEY         IN VARCHAR2,
        P_REQUESTED_BY       IN VARCHAR2,
        P_SUBMISSION_KEY     IN VARCHAR2 DEFAULT NULL,
        P_CYCLE_ID           OUT NUMBER
    ) IS
        L_ROUTING_ID         NUMBER;
        L_VERSION_ID         NUMBER;
        L_DECISION_RULE      VARCHAR2(30);
        L_REQUIRED_APPROVALS NUMBER;
        L_LEGACY_FLOW_MODE   VARCHAR2(20);
        L_SUBMISSION_KEY     VARCHAR2(64);
        L_VOTER_COUNT        PLS_INTEGER;
        L_WORKFLOW_ID        NUMBER;
        L_PARAMETERS         APEX_WORKFLOW.T_WORKFLOW_PARAMETERS;
        L_EXISTING_STATUS    PRC_APPROVAL_CYCLES.CYCLE_STATUS%TYPE;
    BEGIN
        P_CYCLE_ID := NULL;

        IF P_SOURCE_KEY IS NULL OR P_REQUESTED_BY IS NULL THEN
            RAISE_APPLICATION_ERROR(-20031, 'A source request key and initiator are required.');
        END IF;

        BEGIN
            FIND_ROUTE(P_SOURCE_APP_ID, P_SOURCE_ENTITY_CODE, P_SOURCE_TYPE_ID,
                       L_ROUTING_ID, L_VERSION_ID, L_DECISION_RULE,
                       L_REQUIRED_APPROVALS, L_LEGACY_FLOW_MODE);
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RETURN;
        END;

        L_SUBMISSION_KEY := SUBSTR(
            COALESCE(TRIM(P_SUBMISSION_KEY), 'INITIAL-' || TRIM(P_SOURCE_KEY)),
            1,
            64
        );

        BEGIN
            SELECT CYCLE_ID, CYCLE_STATUS
              INTO P_CYCLE_ID, L_EXISTING_STATUS
              FROM PRC_APPROVAL_CYCLES
             WHERE SOURCE_APP_ID = P_SOURCE_APP_ID
               AND SOURCE_ENTITY_CODE = UPPER(TRIM(P_SOURCE_ENTITY_CODE))
               AND SOURCE_KEY = TRIM(P_SOURCE_KEY)
               AND SUBMISSION_KEY = L_SUBMISSION_KEY;
            RETURN;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                NULL;
        END;

        BEGIN
            INSERT INTO PRC_APPROVAL_CYCLES (
                SOURCE_APP_ID,
                SOURCE_ENTITY_CODE,
                SOURCE_TYPE_ID,
                SOURCE_KEY,
                SUBMISSION_KEY,
                VERSION_ID,
                DECISION_RULE,
                REQUIRED_APPROVALS,
                CYCLE_STATUS,
                REQUESTED_BY
            ) VALUES (
                P_SOURCE_APP_ID,
                UPPER(TRIM(P_SOURCE_ENTITY_CODE)),
                P_SOURCE_TYPE_ID,
                TRIM(P_SOURCE_KEY),
                L_SUBMISSION_KEY,
                L_VERSION_ID,
                L_DECISION_RULE,
                NVL(L_REQUIRED_APPROVALS, 1),
                'PREPARING',
                TRIM(P_REQUESTED_BY)
            ) RETURNING CYCLE_ID INTO P_CYCLE_ID;
        EXCEPTION
            WHEN DUP_VAL_ON_INDEX THEN
                BEGIN
                    SELECT CYCLE_ID
                      INTO P_CYCLE_ID
                      FROM PRC_APPROVAL_CYCLES
                     WHERE SOURCE_APP_ID = P_SOURCE_APP_ID
                       AND SOURCE_ENTITY_CODE = UPPER(TRIM(P_SOURCE_ENTITY_CODE))
                       AND SOURCE_KEY = TRIM(P_SOURCE_KEY)
                       AND SUBMISSION_KEY = L_SUBMISSION_KEY;
                EXCEPTION
                    WHEN NO_DATA_FOUND THEN
                        SELECT CYCLE_ID
                          INTO P_CYCLE_ID
                          FROM PRC_APPROVAL_CYCLES
                         WHERE SOURCE_APP_ID = P_SOURCE_APP_ID
                           AND SOURCE_ENTITY_CODE = UPPER(TRIM(P_SOURCE_ENTITY_CODE))
                           AND SOURCE_KEY = TRIM(P_SOURCE_KEY)
                           AND CYCLE_STATUS IN ('PREPARING', 'PENDING');
                END;
                RETURN;
        END;

        INSERT INTO PRC_APPROVAL_VOTERS (
            CYCLE_ID,
            MEMBER_ID,
            EMPLOYEE_NUMBER,
            EMPLOYEE_NAME,
            APP_USER,
            ROLE_NAME_SNAPSHOT,
            SPECIALTY_SNAPSHOT,
            VOTE_STATUS
        )
        SELECT P_CYCLE_ID,
               M.MEMBER_ID,
               M.EMPLOYEE_NUMBER,
               M.EMPLOYEE_NAME,
               M.APP_USER,
               R.ROLE_NAME,
               S.SPECIALTY_NAME,
               'PENDING'
          FROM PRC_COMMITTEE_MEMBERS M
          JOIN PRC_COMMITTEE_ROLE_TYPES R
            ON R.ROLE_TYPE_ID = M.ROLE_TYPE_ID
          JOIN PRC_COMMITTEE_SPECIALTIES S
            ON S.SPECIALTY_ID = M.SPECIALTY_ID
         WHERE M.VERSION_ID = L_VERSION_ID
           AND M.VOTING_ENABLED = 'Y'
           AND R.IS_ACTIVE = 'Y'
           AND S.IS_ACTIVE = 'Y'
         ORDER BY M.SORT_ORDER, M.MEMBER_ID;

        L_VOTER_COUNT := SQL%ROWCOUNT;
        INSERT INTO PRC_FINAL_DECISIONS(CYCLE_ID,CHAIR_VOTER_ID,APP_USER,EMPLOYEE_NAME)
        SELECT P_CYCLE_ID,V.VOTER_ID,V.APP_USER,V.EMPLOYEE_NAME
          FROM PRC_APPROVAL_VOTERS V
          JOIN PRC_COMMITTEE_MEMBERS M ON M.MEMBER_ID=V.MEMBER_ID
          JOIN PRC_COMMITTEE_ROLE_TYPES R ON R.ROLE_TYPE_ID=M.ROLE_TYPE_ID
         WHERE V.CYCLE_ID=P_CYCLE_ID AND R.ROLE_CODE='CHAIR';
        IF SQL%ROWCOUNT<>1 THEN
            RAISE_APPLICATION_ERROR(-20083,'يجب أن تضم اللجنة رئيسا واحدا.');
        END IF;
        SELECT COUNT(*) INTO L_VOTER_COUNT FROM PRC_APPROVAL_VOTERS
         WHERE CYCLE_ID=P_CYCLE_ID AND UPPER(APP_USER)=UPPER(P_REQUESTED_BY);
        IF L_VOTER_COUNT>0 THEN
            RAISE_APPLICATION_ERROR(-20084,'مقدم الطلب لا يمكنه اعتماد طلبه ضمن اللجنة.');
        END IF;
        SELECT COUNT(*) INTO L_VOTER_COUNT FROM PRC_APPROVAL_VOTERS WHERE CYCLE_ID=P_CYCLE_ID;


        IF L_VOTER_COUNT = 0 OR L_REQUIRED_APPROVALS > L_VOTER_COUNT THEN
            RAISE_APPLICATION_ERROR(-20032, 'The routed committee has no valid voters or an invalid approval threshold.');
        END IF;

        INSERT INTO PRC_APPROVAL_EVENTS (
            CYCLE_ID, EVENT_CODE, EVENT_STATUS, EVENT_BY, EVENT_DETAILS
        ) VALUES (
            P_CYCLE_ID, 'SUBMITTED', 'PENDING', TRIM(P_REQUESTED_BY),
            'Parallel committee voting tasks are being created.'
        );

        UPDATE PRC_APPROVAL_CYCLES
           SET TOTAL_VOTERS = L_VOTER_COUNT,
               CYCLE_STATUS = 'PENDING'
         WHERE CYCLE_ID = P_CYCLE_ID;

        L_PARAMETERS(1) := APEX_WORKFLOW.T_WORKFLOW_PARAMETER(
            STATIC_ID => 'CYCLE_ID',
            STRING_VALUE => TO_CHAR(P_CYCLE_ID)
        );

        L_WORKFLOW_ID := APEX_WORKFLOW.START_WORKFLOW(
            P_APPLICATION_ID => C_APPLICATION_ID,
            P_STATIC_ID      => C_WORKFLOW_STATIC_ID,
            P_PARAMETERS     => L_PARAMETERS,
            P_INITIATOR      => TRIM(P_REQUESTED_BY),
            P_DETAIL_PK      => TO_CHAR(P_CYCLE_ID)
        );

        UPDATE PRC_APPROVAL_CYCLES
           SET WORKFLOW_ID = L_WORKFLOW_ID
         WHERE CYCLE_ID = P_CYCLE_ID;
    END SUBMIT_REQUEST;

    PROCEDURE CREATE_PARALLEL_TASKS (P_CYCLE_ID IN NUMBER) IS
        L_CYCLE      PRC_APPROVAL_CYCLES%ROWTYPE;
        L_PARAMETERS APEX_HUMAN_TASK.T_TASK_PARAMETERS;
        L_TASK_ID    NUMBER;
    BEGIN
        SELECT *
          INTO L_CYCLE
          FROM PRC_APPROVAL_CYCLES
         WHERE CYCLE_ID = P_CYCLE_ID
           FOR UPDATE;

        IF L_CYCLE.CYCLE_STATUS <> 'PENDING' THEN
            RETURN;
        END IF;

        FOR V IN (
            SELECT VOTER_ID,
                   EMPLOYEE_NUMBER,
                   EMPLOYEE_NAME,
                   ROLE_NAME_SNAPSHOT,
                   SPECIALTY_SNAPSHOT
              FROM PRC_APPROVAL_VOTERS
             WHERE CYCLE_ID = P_CYCLE_ID
               AND VOTE_STATUS = 'PENDING'
               AND TASK_ID IS NULL
             ORDER BY VOTER_ID
             FOR UPDATE
        ) LOOP
            L_PARAMETERS.DELETE;
            L_PARAMETERS(1) := APEX_HUMAN_TASK.T_TASK_PARAMETER(
                STATIC_ID => 'CYCLE_ID', STRING_VALUE => TO_CHAR(P_CYCLE_ID));
            L_PARAMETERS(2) := APEX_HUMAN_TASK.T_TASK_PARAMETER(
                STATIC_ID => 'VOTER_ID', STRING_VALUE => TO_CHAR(V.VOTER_ID));
            L_PARAMETERS(3) := APEX_HUMAN_TASK.T_TASK_PARAMETER(
                STATIC_ID => 'EMPLOYEE_NUMBER', STRING_VALUE => V.EMPLOYEE_NUMBER);
            L_PARAMETERS(4) := APEX_HUMAN_TASK.T_TASK_PARAMETER(
                STATIC_ID => 'EMPLOYEE_NAME', STRING_VALUE => V.EMPLOYEE_NAME);
            L_PARAMETERS(5) := APEX_HUMAN_TASK.T_TASK_PARAMETER(
                STATIC_ID => 'SPECIALTY', STRING_VALUE => V.SPECIALTY_SNAPSHOT);
            L_PARAMETERS(6) := APEX_HUMAN_TASK.T_TASK_PARAMETER(
                STATIC_ID => 'REQUEST_KEY', STRING_VALUE => L_CYCLE.SOURCE_KEY);
            L_PARAMETERS(7) := APEX_HUMAN_TASK.T_TASK_PARAMETER(
                STATIC_ID => 'DECISION_REASON', STRING_VALUE => NULL);

            L_TASK_ID := APEX_HUMAN_TASK.CREATE_TASK(
                P_APPLICATION_ID     => C_APPLICATION_ID,
                P_TASK_DEF_STATIC_ID => C_TASK_DEFINITION_STATIC_ID,
                P_SUBJECT            => 'رأي ' || V.ROLE_NAME_SNAPSHOT || ' (' || V.SPECIALTY_SNAPSHOT || ') — ' ||
                                        CASE L_CYCLE.SOURCE_TYPE_ID
                                            WHEN 44 THEN 'قرض اجتماعي'
                                            WHEN 43 THEN 'قرض زواج'
                                            WHEN 45 THEN 'طلب عمرة'
                                            WHEN 46 THEN 'طلب حج'
                                            ELSE 'طلب'
                                        END || ' رقم ' || L_CYCLE.SOURCE_KEY,
                P_PARAMETERS         => L_PARAMETERS,
                P_INITIATOR          => L_CYCLE.REQUESTED_BY,
                P_DETAIL_PK          => TO_CHAR(V.VOTER_ID)
            );

            UPDATE PRC_APPROVAL_VOTERS
               SET TASK_ID = L_TASK_ID
             WHERE VOTER_ID = V.VOTER_ID;

            INSERT INTO PRC_APPROVAL_EVENTS (
                CYCLE_ID, VOTER_ID, EVENT_CODE, EVENT_STATUS, EVENT_BY, EVENT_DETAILS
            ) VALUES (
                P_CYCLE_ID, V.VOTER_ID, 'TASK_CREATED', 'PENDING',
                L_CYCLE.REQUESTED_BY, 'APEX Task ID ' || TO_CHAR(L_TASK_ID)
            );
        END LOOP;
    END CREATE_PARALLEL_TASKS;

    PROCEDURE RECORD_VOTE (
        P_VOTER_ID IN NUMBER, P_TASK_ID IN NUMBER, P_OUTCOME IN VARCHAR2,
        P_ACTOR IN VARCHAR2, P_REASON IN VARCHAR2 DEFAULT NULL
    ) IS
        L_CYCLE_ID NUMBER;
        L_CYCLE PRC_APPROVAL_CYCLES%ROWTYPE;
        L_VOTER PRC_APPROVAL_VOTERS%ROWTYPE;
        L_COUNT NUMBER;
        L_PENDING NUMBER;
        L_PARAMS APEX_HUMAN_TASK.T_TASK_PARAMETERS;
        L_TASK_ID NUMBER;
        L_FINAL PRC_FINAL_DECISIONS%ROWTYPE;
    BEGIN
        IF P_OUTCOME IS NULL OR P_OUTCOME NOT IN ('APPROVED','REJECTED') THEN
            RAISE_APPLICATION_ERROR(-20071,'قرار غير صحيح.');
        END IF;
        IF P_OUTCOME='REJECTED' AND TRIM(P_REASON) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20072,'سبب الرفض مطلوب.');
        END IF;
        SELECT CYCLE_ID INTO L_CYCLE_ID FROM PRC_APPROVAL_VOTERS WHERE VOTER_ID=P_VOTER_ID;
        SELECT * INTO L_CYCLE FROM PRC_APPROVAL_CYCLES WHERE CYCLE_ID=L_CYCLE_ID FOR UPDATE;
        SELECT * INTO L_VOTER FROM PRC_APPROVAL_VOTERS WHERE VOTER_ID=P_VOTER_ID FOR UPDATE;
        SELECT COUNT(*) INTO L_COUNT FROM APEX_TASKS
         WHERE TASK_ID=P_TASK_ID AND APPLICATION_ID=C_APPLICATION_ID
           AND TASK_DEF_STATIC_ID=C_TASK_DEFINITION_STATIC_ID
           AND UPPER(ACTUAL_OWNER)=UPPER(P_ACTOR);
        IF L_COUNT<>1 OR NVL(L_VOTER.TASK_ID,-1)<>P_TASK_ID OR P_TASK_ID IS NULL
           OR UPPER(L_VOTER.APP_USER)<>UPPER(P_ACTOR) THEN
            RAISE_APPLICATION_ERROR(-20073,'لا يمكنك تسجيل قرار لمهمة عضو آخر.');
        END IF;
        IF L_VOTER.VOTE_STATUS<>'PENDING' THEN RETURN; END IF;
        IF L_CYCLE.CYCLE_STATUS<>'PENDING' THEN
            RAISE_APPLICATION_ERROR(-20074,'دورة الاعتماد مغلقة.');
        END IF;
        UPDATE PRC_APPROVAL_VOTERS SET VOTE_STATUS=P_OUTCOME,DECIDED_BY=P_ACTOR,
            DECIDED_AT=SYSTIMESTAMP,DECISION_REASON=P_REASON WHERE VOTER_ID=P_VOTER_ID;
        INSERT INTO PRC_APPROVAL_EVENTS(CYCLE_ID,VOTER_ID,EVENT_CODE,EVENT_STATUS,EVENT_BY,EVENT_DETAILS)
        VALUES(L_CYCLE_ID,P_VOTER_ID,'VOTE_RECORDED',P_OUTCOME,P_ACTOR,P_REASON);
        SELECT COUNT(CASE WHEN VOTE_STATUS='PENDING' THEN 1 END) INTO L_PENDING
          FROM PRC_APPROVAL_VOTERS WHERE CYCLE_ID=L_CYCLE_ID;
        UPDATE PRC_APPROVAL_CYCLES C SET
            APPROVED_COUNT=(SELECT COUNT(*) FROM PRC_APPROVAL_VOTERS V WHERE V.CYCLE_ID=C.CYCLE_ID AND V.VOTE_STATUS='APPROVED'),
            REJECTED_COUNT=(SELECT COUNT(*) FROM PRC_APPROVAL_VOTERS V WHERE V.CYCLE_ID=C.CYCLE_ID AND V.VOTE_STATUS='REJECTED')
         WHERE C.CYCLE_ID=L_CYCLE_ID;
        IF L_PENDING=0 THEN
            SELECT * INTO L_FINAL FROM PRC_FINAL_DECISIONS WHERE CYCLE_ID=L_CYCLE_ID FOR UPDATE;
            IF L_FINAL.TASK_ID IS NULL THEN
                L_PARAMS(1):=APEX_HUMAN_TASK.T_TASK_PARAMETER(STATIC_ID=>'CYCLE_ID',STRING_VALUE=>TO_CHAR(L_CYCLE_ID));
                L_PARAMS(2):=APEX_HUMAN_TASK.T_TASK_PARAMETER(STATIC_ID=>'DECISION_REASON',STRING_VALUE=>NULL);
                L_TASK_ID:=APEX_HUMAN_TASK.CREATE_TASK(
                    P_APPLICATION_ID=>C_APPLICATION_ID,P_TASK_DEF_STATIC_ID=>'PRC_COMMITTEE_FINAL',
                    P_SUBJECT=>'القرار النهائي لرئيس اللجنة - الطلب '||L_CYCLE.SOURCE_KEY,
                    P_PARAMETERS=>L_PARAMS,P_INITIATOR=>L_CYCLE.REQUESTED_BY,P_DETAIL_PK=>TO_CHAR(L_CYCLE_ID));
                UPDATE PRC_FINAL_DECISIONS SET TASK_ID=L_TASK_ID,DECISION_STATUS='READY' WHERE CYCLE_ID=L_CYCLE_ID;
                INSERT INTO PRC_APPROVAL_EVENTS(CYCLE_ID,EVENT_CODE,EVENT_STATUS,EVENT_BY)
                VALUES(L_CYCLE_ID,'AWAITING_CHAIR','PENDING',P_ACTOR);
            END IF;
        END IF;
    END RECORD_VOTE;

    PROCEDURE RECORD_FINAL_DECISION (
        P_CYCLE_ID IN NUMBER, P_TASK_ID IN NUMBER, P_OUTCOME IN VARCHAR2,
        P_ACTOR IN VARCHAR2, P_REASON IN VARCHAR2
    ) IS
        L_CYCLE PRC_APPROVAL_CYCLES%ROWTYPE;
        L_FINAL PRC_FINAL_DECISIONS%ROWTYPE;
        L_COUNT NUMBER;
        L_PARAMS WWV_FLOW_GLOBAL.VC_MAP;
    BEGIN
        IF P_OUTCOME IS NULL OR P_OUTCOME NOT IN ('APPROVED','REJECTED') THEN
            RAISE_APPLICATION_ERROR(-20075,'قرار غير صحيح.');
        END IF;
        IF TRIM(P_REASON) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20076,'يرجى كتابة قرار اللجنة النهائي وأسبابه.');
        END IF;
        SELECT * INTO L_CYCLE FROM PRC_APPROVAL_CYCLES WHERE CYCLE_ID=P_CYCLE_ID FOR UPDATE;
        SELECT * INTO L_FINAL FROM PRC_FINAL_DECISIONS WHERE CYCLE_ID=P_CYCLE_ID FOR UPDATE;
        SELECT COUNT(*) INTO L_COUNT FROM APEX_TASKS WHERE TASK_ID=P_TASK_ID
            AND APPLICATION_ID=C_APPLICATION_ID AND TASK_DEF_STATIC_ID='PRC_COMMITTEE_FINAL'
            AND UPPER(ACTUAL_OWNER)=UPPER(P_ACTOR);
        IF L_COUNT<>1 OR P_TASK_ID IS NULL OR NVL(L_FINAL.TASK_ID,-1)<>P_TASK_ID
           OR UPPER(L_FINAL.APP_USER)<>UPPER(P_ACTOR) THEN
            RAISE_APPLICATION_ERROR(-20077,'القرار النهائي متاح لرئيس اللجنة المعين فقط.');
        END IF;
        IF L_FINAL.DECISION_STATUS IN ('APPROVED','REJECTED') THEN RETURN; END IF;
        IF L_CYCLE.CYCLE_STATUS<>'PENDING' OR L_FINAL.DECISION_STATUS<>'READY' THEN
            RAISE_APPLICATION_ERROR(-20078,'الطلب غير جاهز للقرار النهائي.');
        END IF;
        SELECT COUNT(*) INTO L_COUNT FROM PRC_APPROVAL_VOTERS WHERE CYCLE_ID=P_CYCLE_ID AND VOTE_STATUS='PENDING';
        IF L_COUNT<>0 THEN RAISE_APPLICATION_ERROR(-20079,'يجب استكمال آراء جميع الأعضاء أولا.'); END IF;
        UPDATE PRC_FINAL_DECISIONS SET DECISION_STATUS=P_OUTCOME,DECISION_REASON=P_REASON,
            DECIDED_BY=P_ACTOR,DECIDED_AT=SYSTIMESTAMP WHERE CYCLE_ID=P_CYCLE_ID;
        UPDATE PRC_APPROVAL_CYCLES SET CYCLE_STATUS=P_OUTCOME,FINAL_DECISION_BY=P_ACTOR,
            FINISHED_AT=SYSTIMESTAMP WHERE CYCLE_ID=P_CYCLE_ID;
        INSERT INTO PRC_APPROVAL_EVENTS(CYCLE_ID,EVENT_CODE,EVENT_STATUS,EVENT_BY,EVENT_DETAILS)
        VALUES(P_CYCLE_ID,'CHAIR_FINAL_DECISION',P_OUTCOME,P_ACTOR,P_REASON);
        INSERT INTO PRC_APPROVAL_OUTBOX(CYCLE_ID,EVENT_CODE,DEDUPE_KEY,PAYLOAD)
        VALUES(P_CYCLE_ID,'COMMITTEE_DECISION','COMMITTEE_DECISION:'||P_CYCLE_ID,'status='||P_OUTCOME);
        PRC_REQUEST_ADAPTER_PKG.APPLY_SOCIAL_LOAN_DECISION(P_CYCLE_ID);
        APEX_WORKFLOW.CONTINUE_ACTIVITY(P_INSTANCE_ID=>L_CYCLE.WORKFLOW_ID,
            P_STATIC_ID=>C_WAIT_ACTIVITY_STATIC_ID,P_ACTIVITY_PARAMS=>L_PARAMS);
    END RECORD_FINAL_DECISION;

    PROCEDURE COMPLETE_MEMBER_TASK (
        P_TASK_ID IN NUMBER, P_OUTCOME IN VARCHAR2, P_REASON IN VARCHAR2
    ) IS
        L_COUNT NUMBER;
        L_PARAMS APEX_HUMAN_TASK.T_TASK_PARAMETERS;
        L_USER VARCHAR2(255):=V('APP_USER');
    BEGIN
        IF L_USER IS NULL OR LOWER(L_USER) IN ('nobody','apex_public_user') THEN
            RAISE_APPLICATION_ERROR(-20080,'يجب تسجيل الدخول.');
        END IF;
        SELECT COUNT(*) INTO L_COUNT FROM (
            SELECT TASK_ID,APP_USER FROM PRC_APPROVAL_VOTERS WHERE VOTE_STATUS='PENDING'
            UNION ALL SELECT TASK_ID,APP_USER FROM PRC_FINAL_DECISIONS WHERE DECISION_STATUS='READY'
        ) WHERE TASK_ID=P_TASK_ID AND UPPER(APP_USER)=UPPER(L_USER);
        IF L_COUNT<>1 THEN RAISE_APPLICATION_ERROR(-20081,'هذه المهمة غير متاحة لك.'); END IF;
        IF P_OUTCOME IS NULL OR P_OUTCOME NOT IN ('APPROVED','REJECTED') THEN
            RAISE_APPLICATION_ERROR(-20082,'قرار غير صحيح.');
        END IF;
        -- Validate before invoking the APEX completion API. A failing completion
        -- action can leave the task errored rather than available for correction.
        IF P_OUTCOME='REJECTED' AND TRIM(P_REASON) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20072,'سبب الرفض مطلوب.');
        END IF;
        SELECT COUNT(*) INTO L_COUNT FROM PRC_FINAL_DECISIONS
         WHERE TASK_ID=P_TASK_ID AND DECISION_STATUS='READY';
        IF L_COUNT=1 AND TRIM(P_REASON) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20076,'يرجى كتابة قرار اللجنة النهائي وأسبابه.');
        END IF;
        L_PARAMS(1):=APEX_HUMAN_TASK.T_TASK_PARAMETER(STATIC_ID=>'DECISION_REASON',STRING_VALUE=>P_REASON);
        APEX_HUMAN_TASK.SET_TASK_PARAMETER_VALUES(P_TASK_ID=>P_TASK_ID,P_PARAMETERS=>L_PARAMS);
        APEX_HUMAN_TASK.COMPLETE_TASK(P_TASK_ID=>P_TASK_ID,P_OUTCOME=>P_OUTCOME,P_AUTOCLAIM=>TRUE);
    END COMPLETE_MEMBER_TASK;

    FUNCTION IS_CYCLE_COMPLETE (P_CYCLE_ID IN NUMBER) RETURN BOOLEAN IS
        L_COUNT PLS_INTEGER;
    BEGIN
        SELECT COUNT(*)
          INTO L_COUNT
          FROM PRC_APPROVAL_CYCLES
         WHERE CYCLE_ID = P_CYCLE_ID
           AND CYCLE_STATUS IN ('APPROVED', 'REJECTED', 'CANCELLED');
        RETURN L_COUNT = 1;
    END IS_CYCLE_COMPLETE;

    PROCEDURE CANCEL_CYCLE (
        P_CYCLE_ID IN NUMBER,
        P_ACTOR    IN VARCHAR2,
        P_REASON   IN VARCHAR2
    ) IS
        L_WORKFLOW_ID PRC_APPROVAL_CYCLES.WORKFLOW_ID%TYPE;
        L_STATUS      PRC_APPROVAL_CYCLES.CYCLE_STATUS%TYPE;
        L_ACTIVITY_PARAMS WWV_FLOW_GLOBAL.VC_MAP;
    BEGIN
        IF NOT PRC_COMMITTEE_PKG.IS_WORKFLOW_ADMIN(P_ACTOR) THEN
            RAISE_APPLICATION_ERROR(-20040, 'Workflow administrator privileges are required to cancel an approval cycle.');
        END IF;

        SELECT WORKFLOW_ID, CYCLE_STATUS
          INTO L_WORKFLOW_ID, L_STATUS
          FROM PRC_APPROVAL_CYCLES
         WHERE CYCLE_ID = P_CYCLE_ID
           FOR UPDATE;

        IF L_STATUS <> 'PENDING' THEN
            RAISE_APPLICATION_ERROR(-20039, 'Only a pending committee cycle can be canceled.');
        END IF;

        IF TRIM(P_REASON) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20085,'سبب إلغاء الدورة مطلوب.');
        END IF;

        FOR F IN (
            SELECT TASK_ID FROM PRC_FINAL_DECISIONS
             WHERE CYCLE_ID=P_CYCLE_ID AND DECISION_STATUS='READY' AND TASK_ID IS NOT NULL
        ) LOOP
            APEX_HUMAN_TASK.CANCEL_TASK(P_TASK_ID=>F.TASK_ID);
        END LOOP;
        UPDATE PRC_FINAL_DECISIONS SET DECISION_STATUS='CANCELLED'
         WHERE CYCLE_ID=P_CYCLE_ID AND DECISION_STATUS IN ('WAITING','READY');

        FOR T IN (
            SELECT V.TASK_ID
              FROM PRC_APPROVAL_VOTERS V
              JOIN APEX_TASKS T ON T.TASK_ID=V.TASK_ID
             WHERE V.CYCLE_ID = P_CYCLE_ID
               AND V.VOTE_STATUS = 'PENDING'
               AND T.APPLICATION_ID=C_APPLICATION_ID
               AND T.STATE_CODE IN ('UNASSIGNED','ASSIGNED')
        ) LOOP
            APEX_HUMAN_TASK.CANCEL_TASK(P_TASK_ID => T.TASK_ID);
        END LOOP;

        UPDATE PRC_APPROVAL_CYCLES
           SET CYCLE_STATUS = 'CANCELLED',
               FINISHED_AT = SYSTIMESTAMP,
               FINAL_DECISION_BY = TRIM(P_ACTOR)
         WHERE CYCLE_ID = P_CYCLE_ID;

        UPDATE PRC_APPROVAL_VOTERS
           SET VOTE_STATUS = 'CANCELLED'
         WHERE CYCLE_ID = P_CYCLE_ID
           AND VOTE_STATUS = 'PENDING';

        INSERT INTO PRC_APPROVAL_EVENTS (
            CYCLE_ID, EVENT_CODE, EVENT_STATUS, EVENT_BY, EVENT_DETAILS
        ) VALUES (
            P_CYCLE_ID, 'CYCLE_CANCELLED', 'CANCELLED', TRIM(P_ACTOR), P_REASON
        );

        PRC_REQUEST_ADAPTER_PKG.APPLY_SOCIAL_LOAN_DECISION(P_CYCLE_ID);
        IF L_WORKFLOW_ID IS NOT NULL THEN
            APEX_WORKFLOW.CONTINUE_ACTIVITY(
                P_INSTANCE_ID     => L_WORKFLOW_ID,
                P_STATIC_ID       => C_WAIT_ACTIVITY_STATIC_ID,
                P_ACTIVITY_PARAMS => L_ACTIVITY_PARAMS
            );
        END IF;
    END CANCEL_CYCLE;
END PRC_APPROVAL_PKG;
