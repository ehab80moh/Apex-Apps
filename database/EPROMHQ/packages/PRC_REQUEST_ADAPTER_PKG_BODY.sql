
  CREATE OR REPLACE EDITIONABLE PACKAGE BODY "EPROMHQ"."PRC_REQUEST_ADAPTER_PKG" AS
    FUNCTION SOCIAL_LOAN_VALIDATION(P_EMPLOYEE_NUMBER IN VARCHAR2) RETURN VARCHAR2 IS
        L_COUNT NUMBER;
        L_VERSION_ID NUMBER;
        L_MODE VARCHAR2(20);
    BEGIN
        IF P_EMPLOYEE_NUMBER IS NULL THEN RETURN 'يجب تحديد الموظف مقدم الطلب.'; END IF;
        IF V('APP_USER') IS NULL OR LOWER(V('APP_USER')) IN ('nobody','apex_public_user') THEN
            RETURN 'يجب تسجيل الدخول لتقديم الطلب.';
        END IF;
        SELECT COUNT(*) INTO L_COUNT FROM CENTRAL.XXAPEX_HR_EMP_DATA
         WHERE TRIM(EMP_NUMBER)=TRIM(P_EMPLOYEE_NUMBER);
        IF L_COUNT=0 THEN RETURN 'الموظف مقدم الطلب غير موجود في دليل الشركة.'; END IF;
        IF UPPER(P_EMPLOYEE_NUMBER)<>UPPER(V('APP_USER'))
           AND NOT PRC_COMMITTEE_PKG.IS_COMMITTEE_ADMIN(V('APP_USER')) THEN
            RETURN 'لا تملك صلاحية تقديم الطلب نيابة عن هذا الموظف.';
        END IF;
        SELECT COUNT(*),MAX(R.VERSION_ID),MAX(R.LEGACY_FLOW_MODE)
          INTO L_COUNT,L_VERSION_ID,L_MODE
          FROM PRC_COMMITTEE_ROUTING R JOIN PRC_COMMITTEE_VERSIONS V ON V.VERSION_ID=R.VERSION_ID
         WHERE R.SOURCE_APP_ID=105 AND R.SOURCE_ENTITY_CODE='PRF_LOANS_REQUEST'
           AND R.SOURCE_TYPE_ID=44 AND R.IS_ACTIVE='Y' AND V.VERSION_STATUS='ACTIVE'
           AND (R.EFFECTIVE_FROM IS NULL OR R.EFFECTIVE_FROM<TRUNC(SYSDATE)+1)
           AND (R.EFFECTIVE_TO IS NULL OR R.EFFECTIVE_TO>=TRUNC(SYSDATE))
           AND (V.EFFECTIVE_FROM IS NULL OR V.EFFECTIVE_FROM<TRUNC(SYSDATE)+1)
           AND (V.EFFECTIVE_TO IS NULL OR V.EFFECTIVE_TO>=TRUNC(SYSDATE));
        IF L_COUNT<>1 THEN RETURN 'يلزم ربط واحد صالح للقرض الاجتماعي بتشكيل لجنة فعال وساري.'; END IF;
        IF L_MODE<>'REPLACE' THEN RETURN 'ربط القرض الاجتماعي يجب أن يستبدل مسار الموافقات السابق بمسار اللجنة.'; END IF;
        SELECT COUNT(*) INTO L_COUNT FROM PRC_COMMITTEE_MEMBERS M
         JOIN PRC_COMMITTEE_ROLE_TYPES R ON R.ROLE_TYPE_ID=M.ROLE_TYPE_ID
         WHERE M.VERSION_ID=L_VERSION_ID AND M.VOTING_ENABLED='Y'
           AND R.ROLE_CODE='CHAIR' AND R.IS_ACTIVE='Y';
        IF L_COUNT<>1 THEN RETURN 'يجب تحديد رئيس واحد مصوت للجنة.'; END IF;
        SELECT COUNT(*) INTO L_COUNT FROM PRC_COMMITTEE_MEMBERS M
         WHERE M.VERSION_ID=L_VERSION_ID AND M.VOTING_ENABLED='Y'
           AND UPPER(M.APP_USER)=UPPER(P_EMPLOYEE_NUMBER);
        IF L_COUNT>0 THEN RETURN 'مقدم الطلب عضو مصوت في اللجنة؛ يلزم تشكيل لا يتيح له اعتماد طلبه.'; END IF;
        SELECT COUNT(*) INTO L_COUNT FROM PRC_COMMITTEE_MEMBERS M
         JOIN PRC_COMMITTEE_ROLE_TYPES R ON R.ROLE_TYPE_ID=M.ROLE_TYPE_ID
         JOIN PRC_COMMITTEE_SPECIALTIES S ON S.SPECIALTY_ID=M.SPECIALTY_ID
         WHERE M.VERSION_ID=L_VERSION_ID AND M.VOTING_ENABLED='Y'
           AND (R.IS_ACTIVE<>'Y' OR S.IS_ACTIVE<>'Y'
                OR NOT EXISTS (SELECT 1 FROM CENTRAL.XXAPEX_HR_EMP_DATA E WHERE TRIM(E.EMP_NUMBER)=M.EMPLOYEE_NUMBER));
        IF L_COUNT>0 THEN RETURN 'بيانات أحد أعضاء اللجنة أو صفته أو تخصصه غير صالحة.'; END IF;
        RETURN NULL;
    END SOCIAL_LOAN_VALIDATION;

    PROCEDURE CREATE_SOCIAL_LOAN_REQUEST(
        P_EMPLOYEE_NUMBER IN VARCHAR2, P_AMOUNT IN VARCHAR2,
        P_SUBMISSION_KEY IN VARCHAR2, P_REQUEST_ID OUT NUMBER
    ) IS
        L_ERROR VARCHAR2(4000);
        L_EMPLOYEE VARCHAR2(255);
        L_AMOUNT PRF_LOANS_REQUEST.AMOUNT_REQUIRED%TYPE;
    BEGIN
        L_ERROR:=SOCIAL_LOAN_VALIDATION(P_EMPLOYEE_NUMBER);
        IF L_ERROR IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20092,L_ERROR); END IF;
        IF P_SUBMISSION_KEY IS NULL OR LENGTH(P_SUBMISSION_KEY)>64 OR TRIM(P_AMOUNT) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20097,'بيانات إرسال الطلب غير مكتملة؛ أعد فتح نموذج الطلب.');
        END IF;
        BEGIN
            INSERT INTO PRC_SOCIAL_SUBMISSIONS(SUBMISSION_KEY,EMPLOYEE_NUMBER,CREATED_BY)
            VALUES(P_SUBMISSION_KEY,P_EMPLOYEE_NUMBER,V('APP_USER'));
        EXCEPTION WHEN DUP_VAL_ON_INDEX THEN
            SELECT S.REQUEST_ID,S.EMPLOYEE_NUMBER,R.AMOUNT_REQUIRED
              INTO P_REQUEST_ID,L_EMPLOYEE,L_AMOUNT
              FROM PRC_SOCIAL_SUBMISSIONS S JOIN PRF_LOANS_REQUEST R ON R.REQUEST_ID=S.REQUEST_ID
             WHERE S.SUBMISSION_KEY=P_SUBMISSION_KEY FOR UPDATE OF S.REQUEST_ID;
            IF UPPER(L_EMPLOYEE)<>UPPER(P_EMPLOYEE_NUMBER) OR L_AMOUNT<>P_AMOUNT THEN
                RAISE_APPLICATION_ERROR(-20098,'تم استخدام جلسة الإرسال هذه لطلب آخر؛ أعد فتح النموذج.');
            END IF;
            RETURN;
        END;
        INSERT INTO PRF_LOANS_REQUEST(EMP_ID,REQUEST_TYPE_ID,TEXT_DATA,AMOUNT_REQUIRED,REQUEST_DATE,CREATED_AT,UPDATED_BY,APPROVAL_GM_PR)
        VALUES(TO_NUMBER(P_EMPLOYEE_NUMBER),'44',P_AMOUNT,P_AMOUNT,SYSDATE,SYSDATE,V('APP_USER'),0)
        RETURNING REQUEST_ID INTO P_REQUEST_ID;
        UPDATE PRC_SOCIAL_SUBMISSIONS SET REQUEST_ID=P_REQUEST_ID WHERE SUBMISSION_KEY=P_SUBMISSION_KEY;
    END CREATE_SOCIAL_LOAN_REQUEST;

    PROCEDURE SUBMIT_PRF_LOAN_REQUEST (
        P_REQUEST_ID IN NUMBER, P_REQUEST_TYPE_ID IN NUMBER,
        P_REQUESTED_BY IN VARCHAR2, P_CYCLE_ID OUT NUMBER
    ) IS
        L_EMPLOYEE_NUMBER VARCHAR2(255);
        L_ERROR VARCHAR2(4000);
    BEGIN
        IF P_REQUEST_TYPE_ID NOT IN (43,44) THEN P_CYCLE_ID:=NULL; RETURN; END IF;
        IF P_REQUEST_TYPE_ID=44 THEN
            SELECT TO_CHAR(EMP_ID) INTO L_EMPLOYEE_NUMBER FROM PRF_LOANS_REQUEST
             WHERE REQUEST_ID=P_REQUEST_ID AND REQUEST_TYPE_ID='44' AND NVL(DELETE_APPROVED,0)<>1
             FOR UPDATE;
            IF UPPER(L_EMPLOYEE_NUMBER)<>UPPER(P_REQUESTED_BY) OR P_REQUESTED_BY IS NULL THEN
                RAISE_APPLICATION_ERROR(-20091,'مقدم الطلب لا يطابق الموظف المسجل على الطلب.');
            END IF;
            L_ERROR:=SOCIAL_LOAN_VALIDATION(L_EMPLOYEE_NUMBER);
            IF L_ERROR IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20092,L_ERROR); END IF;
        END IF;
        PRC_APPROVAL_PKG.SUBMIT_REQUEST(
            P_SOURCE_APP_ID=>105,P_SOURCE_ENTITY_CODE=>'PRF_LOANS_REQUEST',
            P_SOURCE_TYPE_ID=>P_REQUEST_TYPE_ID,P_SOURCE_KEY=>TO_CHAR(P_REQUEST_ID),
            P_REQUESTED_BY=>P_REQUESTED_BY,P_SUBMISSION_KEY=>'INITIAL-'||TO_CHAR(P_REQUEST_ID),P_CYCLE_ID=>P_CYCLE_ID);
        IF P_REQUEST_TYPE_ID=44 THEN
            IF P_CYCLE_ID IS NULL THEN RAISE_APPLICATION_ERROR(-20093,'لم تبدأ دورة اعتماد اللجنة.'); END IF;
            UPDATE PRF_LOANS_REQUEST SET APPROVAL_GM_PR=0
             WHERE REQUEST_ID=P_REQUEST_ID AND REQUEST_TYPE_ID='44'
               AND EXISTS (SELECT 1 FROM PRC_APPROVAL_CYCLES C WHERE C.CYCLE_ID=P_CYCLE_ID AND C.CYCLE_STATUS='PENDING');
        END IF;
    END SUBMIT_PRF_LOAN_REQUEST;

    PROCEDURE APPLY_SOCIAL_LOAN_DECISION(P_CYCLE_ID IN NUMBER) IS
        L_CYCLE PRC_APPROVAL_CYCLES%ROWTYPE;
        L_DECISION PRC_FINAL_DECISIONS.DECISION_STATUS%TYPE;
        L_RESULT NUMBER;
    BEGIN
        SELECT * INTO L_CYCLE FROM PRC_APPROVAL_CYCLES WHERE CYCLE_ID=P_CYCLE_ID;
        IF L_CYCLE.SOURCE_APP_ID<>105 OR L_CYCLE.SOURCE_ENTITY_CODE<>'PRF_LOANS_REQUEST'
           OR L_CYCLE.SOURCE_TYPE_ID<>44 THEN RETURN; END IF;
        SELECT DECISION_STATUS INTO L_DECISION FROM PRC_FINAL_DECISIONS WHERE CYCLE_ID=P_CYCLE_ID;
        IF L_CYCLE.CYCLE_STATUS NOT IN ('APPROVED','REJECTED','CANCELLED') OR L_DECISION<>L_CYCLE.CYCLE_STATUS THEN
            RAISE_APPLICATION_ERROR(-20094,'قرار اللجنة النهائي غير مكتمل.');
        END IF;
        L_RESULT:=CASE L_CYCLE.CYCLE_STATUS WHEN 'APPROVED' THEN 1 WHEN 'REJECTED' THEN 2 ELSE 3 END;
        UPDATE PRF_LOANS_REQUEST SET APPROVAL_GM_PR=L_RESULT,LAST_APPROVAL_DATE=SYSDATE
         WHERE REQUEST_ID=TO_NUMBER(L_CYCLE.SOURCE_KEY DEFAULT NULL ON CONVERSION ERROR)
           AND REQUEST_TYPE_ID='44'
           AND EMP_ID=TO_NUMBER(L_CYCLE.REQUESTED_BY DEFAULT NULL ON CONVERSION ERROR);
        IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20095,'تعذر تطبيق قرار اللجنة على الطلب المرتبط.'); END IF;
        UPDATE PRC_APPROVAL_OUTBOX SET OUTBOX_STATUS='DONE',COMPLETED_AT=SYSTIMESTAMP
         WHERE CYCLE_ID=P_CYCLE_ID AND EVENT_CODE='COMMITTEE_DECISION' AND OUTBOX_STATUS<>'DONE';
    END APPLY_SOCIAL_LOAN_DECISION;
END PRC_REQUEST_ADAPTER_PKG;
