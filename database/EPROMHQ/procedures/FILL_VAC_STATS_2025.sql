
  CREATE OR REPLACE EDITIONABLE PROCEDURE "EPROMHQ"."FILL_VAC_STATS_2025" AS
BEGIN
  DELETE FROM VAC_SUMMER_UNIT_STAT_2025;

  INSERT INTO VAC_SUMMER_UNIT_STAT_2025 (
    PROJECT_NAME,
    TOTAL_ELIGIBLE,
    PERCENT_OF_UNITS,
    TOTAL_EMPLOYEES_ELIGIBLE,
    WAITLIST_ASSIGNED,
    CREATED_BY
  )
  SELECT
    e.PROJECT,
    COUNT(CASE WHEN a.STATUS_ID = 1 THEN 1 END) AS TOTAL_ELIGIBLE,
    ROUND(COUNT(DISTINCT a.BLOCK_ID) * 100 / 468, 2) AS PERCENT_OF_UNITS,
    (
      SELECT COUNT(*)
      FROM VAC_SUMMER_APP_VIEW sa
      WHERE sa.PROJECT = e.PROJECT
        AND sa.APPLICATION_STATUS IN ('D','A')
    ) AS TOTAL_EMPLOYEES_ELIGIBLE,
    (
      SELECT COUNT(*)
      FROM VAC_SUMMER_APP_VIEW sa
      WHERE sa.PROJECT = e.PROJECT
        AND sa.APPLICATION_STATUS IN ('D','A')
        AND NOT EXISTS (
          SELECT 1
          FROM VAC_UNIT_ALLOCATION va
          WHERE va.EMP_ID = sa.EMP_ID
            AND va.STATUS_ID = 1
        )
    ) AS WAITLIST_ASSIGNED,
    USER
  FROM
    VAC_UNIT_ALLOCATION a
    JOIN VAC_TRIP_BLOCS_V b ON a.BLOCK_ID = b.BLOC_ID
    JOIN CENTRAL.XXAPEX_HR_EMP_DATA e ON a.EMP_ID = e.EMP_NUMBER
  GROUP BY
    e.PROJECT;

  COMMIT;
END;
