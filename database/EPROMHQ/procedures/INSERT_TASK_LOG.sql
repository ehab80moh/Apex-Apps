
  CREATE OR REPLACE EDITIONABLE PROCEDURE "EPROMHQ"."INSERT_TASK_LOG"
(
  P_TASK_ID IN VARCHAR2
) AS
BEGIN
  insert into task_full_details_log
(TASK_ID,APPLICATION_ID,APPLICATION_NAME,TASK_DEF_STATIC_ID,SUBJECT
,INITIATOR,ACTUAL_OWNER,OUTCOME,CREATED_BY,CREATED_ON,TASK_HISTORY_DATA,TASK_PARAMETERS_DATA
,TASK_PARTICIPANTS_DATA)
select
TASK_ID,APPLICATION_ID,APPLICATION_NAME,TASK_DEF_STATIC_ID,SUBJECT
,INITIATOR,ACTUAL_OWNER,OUTCOME,CREATED_BY,CREATED_ON,TASK_HISTORY_DATA,TASK_PARAMETERS_DATA
,TASK_PARTICIPANTS_DATA
from task_full_details_v where task_id =P_TASK_ID;
commit;

exception when others then null;

END INSERT_TASK_LOG;
/
