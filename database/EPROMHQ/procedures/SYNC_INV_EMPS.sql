
  CREATE OR REPLACE EDITIONABLE PROCEDURE "EPROMHQ"."SYNC_INV_EMPS"
AS
BEGIN
  MERGE INTO EPROMHQ.INV_EMPS tgt
  USING (
    SELECT
      EMP_NUMBER,
      EMP_NAME,
      PROJECT
    FROM CENTRAL.XXAPEX_HR_EMP_DATA
    WHERE EMP_NUMBER IS NOT NULL
  ) src
  ON (tgt.EMP_ID = src.EMP_NUMBER)

  WHEN MATCHED THEN
    UPDATE SET
      tgt.EMP_NAME = src.EMP_NAME,
      tgt.PROJECT = NVL(src.PROJECT, 'N/A'),
      tgt.UPDATED_AT = SYSDATE

  WHEN NOT MATCHED THEN
    INSERT (EMP_ID, EMP_NAME, PROJECT, CREATED_AT, UPDATED_AT)
    VALUES (src.EMP_NUMBER, src.EMP_NAME, NVL(src.PROJECT, 'N/A'), SYSDATE, SYSDATE);

  COMMIT;

EXCEPTION
  WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
END SYNC_INV_EMPS;
/
