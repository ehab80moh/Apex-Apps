
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."BI_CARS_TRAFFIC"
  BEFORE INSERT ON "PRF_CARS_REQUEST"
  FOR EACH ROW
BEGIN
  IF :NEW."REQUEST_ID" IS NULL THEN
    SELECT "CARS_TRAFFIC_SEQ".NEXTVAL INTO :NEW."REQUEST_ID" FROM sys.dual;
  END IF;
END;
/
ALTER TRIGGER "EPROMHQ"."BI_CARS_TRAFFIC" ENABLE;
