
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."BI_IIS_TICKETS_STATUS"
BEFORE UPDATE OF STATUS ON EPROMHQ.IIS_TICKETS
FOR EACH ROW
BEGIN
   IF :NEW.STATUS = 'Closed' AND NVL(:OLD.STATUS, 'x') <> 'Closed' THEN
      :NEW.CLOSED_DATE := SYSDATE;
   END IF;
END;
/
ALTER TRIGGER "EPROMHQ"."BI_IIS_TICKETS_STATUS" ENABLE;
