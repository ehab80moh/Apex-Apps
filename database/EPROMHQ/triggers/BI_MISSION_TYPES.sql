
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."BI_MISSION_TYPES"
  BEFORE INSERT ON "PRF_HOTEL_MISSION_TYPES"
  FOR EACH ROW
BEGIN
  IF :NEW."MISSION_ID" IS NULL THEN
    SELECT "MISSION_TYPES_SEQ".NEXTVAL INTO :NEW."MISSION_ID" FROM sys.dual;
  END IF;
END;
/
ALTER TRIGGER "EPROMHQ"."BI_MISSION_TYPES" ENABLE;
