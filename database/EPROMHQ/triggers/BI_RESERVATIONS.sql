
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."BI_RESERVATIONS"
  BEFORE INSERT ON "PRF_HOTEL_REQUEST"
  FOR EACH ROW
BEGIN
  IF :NEW."REQUEST_ID" IS NULL THEN
    SELECT "RESERVATIONS_SEQ".NEXTVAL INTO :NEW."REQUEST_ID" FROM sys.dual;
  END IF;
END;
/
ALTER TRIGGER "EPROMHQ"."BI_RESERVATIONS" ENABLE;
