
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."HR_EMP_DEPENDENTS_BIU"
BEFORE INSERT OR UPDATE ON HR_EMP_DEPENDENTS
FOR EACH ROW
BEGIN
  -- تاريخ الميلاد يجب أن يكون في الماضي
  IF :NEW.BIRTH_DATE IS NOT NULL AND :NEW.BIRTH_DATE >= SYSDATE THEN
    RAISE_APPLICATION_ERROR(-20050, 'Birth date must be in the past.');
  END IF;

  -- مثال ضبط حقول التدقيق
  IF INSERTING THEN
    :NEW.CREATED_AT := NVL(:NEW.CREATED_AT, SYSDATE);
    :NEW.CREATED_BY := NVL(:NEW.CREATED_BY, SYS_CONTEXT('APEX$SESSION','APP_USER'));
  END IF;

  IF UPDATING THEN
    :NEW.UPDATED_AT := SYSDATE;
    :NEW.UPDATED_BY := SYS_CONTEXT('APEX$SESSION','APP_USER');
  END IF;
END;

/
ALTER TRIGGER "EPROMHQ"."HR_EMP_DEPENDENTS_BIU" ENABLE;
