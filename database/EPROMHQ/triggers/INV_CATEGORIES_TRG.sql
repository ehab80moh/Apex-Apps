
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."INV_CATEGORIES_TRG"
before insert on inv_categories
for each row
begin
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.CATEGORY_ID IS NULL THEN
      SELECT INV_CATEGORIES_SEQ.NEXTVAL INTO :NEW.CATEGORY_ID FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
end;
/
ALTER TRIGGER "EPROMHQ"."INV_CATEGORIES_TRG" ENABLE;
