
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."INV_DEPARTMENTS_TRG"
before insert on inv_departments
for each row
begin
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.DEPARTMENT_ID IS NULL THEN
      SELECT INV_DEPARTMENTS_SEQ.NEXTVAL INTO :NEW.DEPARTMENT_ID FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
end;
