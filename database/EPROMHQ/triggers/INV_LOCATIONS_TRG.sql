
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."INV_LOCATIONS_TRG"
BEFORE INSERT ON INV_LOCATIONS
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.LOCATION_ID IS NULL THEN
      SELECT INV_LOCATIONS_SEQ.NEXTVAL INTO :NEW.LOCATION_ID FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;
/
ALTER TRIGGER "EPROMHQ"."INV_LOCATIONS_TRG" ENABLE;
