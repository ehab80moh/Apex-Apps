
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."PRC_APP_USER_ROLES_AUDIT_BIU"
    BEFORE INSERT OR UPDATE ON PRC_APP_USER_ROLES
    FOR EACH ROW
DECLARE
    L_EMPLOYEE_NUMBER CENTRAL.XXAPEX_HR_EMP_DATA.EMP_NUMBER%TYPE;
BEGIN
    :NEW.USER_NAME := TRIM(:NEW.USER_NAME);
    :NEW.ROLE_CODE := UPPER(TRIM(:NEW.ROLE_CODE));
    SELECT EMP_NUMBER
      INTO L_EMPLOYEE_NUMBER
      FROM CENTRAL.XXAPEX_HR_EMP_DATA
     WHERE UPPER(TRIM(EMP_NUMBER)) = UPPER(TRIM(:NEW.USER_NAME))
       AND ROWNUM = 1;
    :NEW.USER_NAME := TRIM(L_EMPLOYEE_NUMBER);
    :NEW.GRANTED_BY := COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER);
    :NEW.GRANTED_AT := SYSTIMESTAMP;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20014, 'Application role user must be present in the read-only HR employee source.');
END;

/
ALTER TRIGGER "EPROMHQ"."PRC_APP_USER_ROLES_AUDIT_BIU" ENABLE;
