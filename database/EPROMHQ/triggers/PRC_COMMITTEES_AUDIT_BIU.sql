
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."PRC_COMMITTEES_AUDIT_BIU"
    BEFORE INSERT OR UPDATE ON PRC_COMMITTEES
    FOR EACH ROW
BEGIN
    IF INSERTING THEN
        :NEW.CREATED_BY := COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER);
        :NEW.CREATED_AT := SYSTIMESTAMP;
    ELSE
        :NEW.UPDATED_BY := COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER);
        :NEW.UPDATED_AT := SYSTIMESTAMP;
    END IF;
END;

/
ALTER TRIGGER "EPROMHQ"."PRC_COMMITTEES_AUDIT_BIU" ENABLE;
