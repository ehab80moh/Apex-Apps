
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."PRC_COMMITTEE_MEMBER_LOCK"
    BEFORE INSERT OR UPDATE OR DELETE ON PRC_COMMITTEE_MEMBERS
    FOR EACH ROW
DECLARE
    l_version_status PRC_COMMITTEE_VERSIONS.VERSION_STATUS%TYPE;
    l_version_id     PRC_COMMITTEE_VERSIONS.VERSION_ID%TYPE;
BEGIN
    l_version_id := CASE WHEN DELETING THEN :OLD.VERSION_ID ELSE :NEW.VERSION_ID END;
    SELECT VERSION_STATUS
      INTO l_version_status
      FROM PRC_COMMITTEE_VERSIONS
     WHERE VERSION_ID = l_version_id;

    IF l_version_status <> 'DRAFT' THEN
        RAISE_APPLICATION_ERROR(-20013, 'Members of an active or retired committee version are immutable. Create a new draft version.');
    END IF;
END;

/
ALTER TRIGGER "EPROMHQ"."PRC_COMMITTEE_MEMBER_LOCK" ENABLE;
