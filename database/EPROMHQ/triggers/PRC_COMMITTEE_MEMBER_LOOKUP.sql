
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."PRC_COMMITTEE_MEMBER_LOOKUP"
    BEFORE INSERT OR UPDATE OF EMPLOYEE_NUMBER ON PRC_COMMITTEE_MEMBERS
    FOR EACH ROW
DECLARE
    L_EMP_NUMBER CENTRAL.XXAPEX_HR_EMP_DATA.EMP_NUMBER%TYPE;
    L_EMP_NAME   CENTRAL.XXAPEX_HR_EMP_DATA.EMP_NAME%TYPE;
BEGIN
    SELECT EMP_NUMBER, EMP_NAME
      INTO L_EMP_NUMBER, L_EMP_NAME
      FROM CENTRAL.XXAPEX_HR_EMP_DATA
     WHERE UPPER(TRIM(EMP_NUMBER)) = UPPER(TRIM(:NEW.EMPLOYEE_NUMBER))
       AND ROWNUM = 1;

    :NEW.EMPLOYEE_NUMBER := TRIM(L_EMP_NUMBER);
    :NEW.EMPLOYEE_NAME := TRIM(L_EMP_NAME);
    :NEW.APP_USER := TRIM(L_EMP_NUMBER);
END;

/
ALTER TRIGGER "EPROMHQ"."PRC_COMMITTEE_MEMBER_LOOKUP" ENABLE;
