
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."PRC_COMMITTEE_VERSIONS_AUDIT_BIU"
    BEFORE INSERT OR UPDATE ON PRC_COMMITTEE_VERSIONS
    FOR EACH ROW
BEGIN
    IF INSERTING THEN
        :NEW.CREATED_BY := COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER);
        :NEW.CREATED_AT := SYSTIMESTAMP;
    END IF;
END;

/
ALTER TRIGGER "EPROMHQ"."PRC_COMMITTEE_VERSIONS_AUDIT_BIU" ENABLE;
