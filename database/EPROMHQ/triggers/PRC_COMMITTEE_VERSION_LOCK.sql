
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."PRC_COMMITTEE_VERSION_LOCK"
    BEFORE UPDATE OR DELETE ON PRC_COMMITTEE_VERSIONS
    FOR EACH ROW
BEGIN
    IF DELETING THEN
        IF :OLD.VERSION_STATUS <> 'DRAFT' THEN
            RAISE_APPLICATION_ERROR(-20011, 'Only draft committee versions can be deleted.');
        END IF;
    ELSIF :OLD.VERSION_STATUS IN ('ACTIVE', 'RETIRED') THEN
        IF NOT (:OLD.VERSION_STATUS = 'ACTIVE' AND :NEW.VERSION_STATUS = 'RETIRED') THEN
            RAISE_APPLICATION_ERROR(-20012, 'An active or retired committee version is immutable. Create a new draft version.');
        END IF;
    END IF;
END;

/
ALTER TRIGGER "EPROMHQ"."PRC_COMMITTEE_VERSION_LOCK" ENABLE;
