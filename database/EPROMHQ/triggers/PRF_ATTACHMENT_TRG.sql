
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."PRF_ATTACHMENT_TRG"
BEFORE INSERT ON PRF_ATTACHMENT
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ATTACH_ID IS NULL THEN
      SELECT PRF_ATTACHMENT_SEQ1.NEXTVAL INTO :NEW.ATTACH_ID FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;
/
ALTER TRIGGER "EPROMHQ"."PRF_ATTACHMENT_TRG" ENABLE;
