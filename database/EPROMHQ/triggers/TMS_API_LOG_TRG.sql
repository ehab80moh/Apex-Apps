
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."TMS_API_LOG_TRG"
BEFORE INSERT ON TMS_API_LOG
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID IS NULL THEN
      SELECT TMS_API_LOG_SEQ.NEXTVAL INTO :NEW.ID FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;
/
ALTER TRIGGER "EPROMHQ"."TMS_API_LOG_TRG" ENABLE;
