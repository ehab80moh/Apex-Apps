
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."TRG_SET_EMP_LAST_BENEFIT"
BEFORE INSERT OR UPDATE ON VAC_SUMMER_APPLICATIONS
FOR EACH ROW
DECLARE
  v_history VAC_HISTORY.HISTORY%TYPE;
BEGIN
  -- نحاول نجيب التاريخ من VAC_HISTORY
  BEGIN
    SELECT distinct HISTORY
    INTO v_history
    FROM VAC_HISTORY
    WHERE EMP_ID = :NEW.EMP_ID;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      v_history := 'لم يستفيد من قبل';
  END;

  -- نحط القيمة في EMP_LAST_BENEFIT
--  :NEW.EMP_LAST_BENEFIT := v_history;

END;
/
ALTER TRIGGER "EPROMHQ"."TRG_SET_EMP_LAST_BENEFIT" ENABLE;
