
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."TRG_SILENT_BLOCK_STATUSS"
BEFORE INSERT OR UPDATE ON EPROMHQ.VAC_UNIT_ALLOCATION
FOR EACH ROW
 WHEN (NEW.STATUS_ID = 1) DECLARE
    l_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO l_count
    FROM EPROMHQ.VAC_UNIT_ALLOCATION
    WHERE EMP_ID = :NEW.EMP_ID
      AND TRIP_ID = :NEW.TRIP_ID
    --   AND BLOCK_ID = :NEW.BLOCK_ID
      AND STATUS_ID = 1
      AND ID <> NVL(:NEW.ID, -1);

    IF l_count > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20002,
            '⚠️ هذا الموظف تم تسكينه بالفعل في نفس الرحلة .'
        );
    END IF;
END;
/
ALTER TRIGGER "EPROMHQ"."TRG_SILENT_BLOCK_STATUSS" ENABLE;
