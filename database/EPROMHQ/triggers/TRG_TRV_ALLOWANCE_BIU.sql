
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."TRG_TRV_ALLOWANCE_BIU"
BEFORE INSERT OR UPDATE ON EPROMHQ.TRV_ALLOWANCE
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        IF :NEW.CREATED_AT IS NULL THEN
            :NEW.CREATED_AT := SYSDATE;
        END IF;

        IF :NEW.CREATED_BY IS NULL THEN
            :NEW.CREATED_BY := NVL(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER);
        END IF;
    END IF;

END;
/
ALTER TRIGGER "EPROMHQ"."TRG_TRV_ALLOWANCE_BIU" ENABLE;
