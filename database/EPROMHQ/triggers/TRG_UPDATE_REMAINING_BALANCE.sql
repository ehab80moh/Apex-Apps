
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."TRG_UPDATE_REMAINING_BALANCE"
FOR INSERT OR DELETE OR UPDATE OF RANDOM_ITEM_ID
ON INV_RANDOM_ITEMS
COMPOUND TRIGGER

  TYPE t_random_ids IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
  v_new_ids t_random_ids;
  v_old_ids t_random_ids;

AFTER EACH ROW IS
BEGIN
  IF INSERTING OR (UPDATING AND :NEW.RANDOM_ITEM_ID IS NOT NULL) THEN
    v_new_ids(v_new_ids.COUNT + 1) := :NEW.RANDOM_ITEM_ID;
  END IF;

  IF DELETING OR (UPDATING AND :OLD.RANDOM_ITEM_ID IS NOT NULL AND :OLD.RANDOM_ITEM_ID != :NEW.RANDOM_ITEM_ID) THEN
    v_old_ids(v_old_ids.COUNT + 1) := :OLD.RANDOM_ITEM_ID;
  END IF;
END AFTER EACH ROW;

AFTER STATEMENT IS
BEGIN
  -- تحديث للقيم الجديدة
  FOR i IN 1 .. v_new_ids.COUNT LOOP
    UPDATE INV_MODEL_RANDOM_ITEMS
    SET REMAINING_BALANCE = TO_CHAR(
        BALANCE - (SELECT COUNT(*) FROM INV_RANDOM_ITEMS WHERE RANDOM_ITEM_ID = v_new_ids(i))
    )
    WHERE ID = v_new_ids(i);
  END LOOP;

  -- تحديث للقيم القديمة
  FOR i IN 1 .. v_old_ids.COUNT LOOP
    UPDATE INV_MODEL_RANDOM_ITEMS
    SET REMAINING_BALANCE = TO_CHAR(
        BALANCE - (SELECT COUNT(*) FROM INV_RANDOM_ITEMS WHERE RANDOM_ITEM_ID = v_old_ids(i))
    )
    WHERE ID = v_old_ids(i);
  END LOOP;
END AFTER STATEMENT;

END trg_update_remaining_balance;

/
ALTER TRIGGER "EPROMHQ"."TRG_UPDATE_REMAINING_BALANCE" ENABLE;
