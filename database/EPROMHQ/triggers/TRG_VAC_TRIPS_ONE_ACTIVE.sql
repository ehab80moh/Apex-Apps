
  CREATE OR REPLACE EDITIONABLE TRIGGER "EPROMHQ"."TRG_VAC_TRIPS_ONE_ACTIVE"
BEFORE INSERT OR UPDATE ON EPROMHQ.VAC_TRIPS
FOR EACH ROW
DECLARE
    v_count NUMBER;
BEGIN
    -- Check if there is already an active trip overlapping with the new one
    SELECT COUNT(*)
    INTO v_count
    FROM EPROMHQ.VAC_TRIPS
    WHERE TRUNC(SYSDATE) BETWEEN APPLICATION_START_DATE AND APPLICATION_END_DATE
      AND TRIP_ID != NVL(:NEW.TRIP_ID, -1);

    IF v_count > 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Cannot have more than one active trip at the same time.');
    END IF;
END;

/
ALTER TRIGGER "EPROMHQ"."TRG_VAC_TRIPS_ONE_ACTIVE" DISABLE;
