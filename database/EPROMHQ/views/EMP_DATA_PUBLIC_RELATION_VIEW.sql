
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "EPROMHQ"."EMP_DATA_PUBLIC_RELATION_VIEW" ("SERIAL_NO", "EMP_NUMBER", "EMP_NAME", "EMP_DATE_OF_BIRTH", "EMP_POSITION_NAME", "GRADE_NAME", "ORGANIZATION_NAME", "PROJECT", "MOBILE", "ASSIGNMENTS_DATE", "PERMANENT_DATE", "EXP_DATE", "CON_TYP", "HIRE_DATE", "FIN_PROJECT", "EGPC_EMAIL", "EMP_ROTATION") AS
  SELECT
  ROW_NUMBER() OVER (ORDER BY d.EMP_DATE_OF_BIRTH ASC) AS SERIAL_NO,
    d.EMP_NUMBER,
    d.EMP_NAME,
    d.EMP_DATE_OF_BIRTH,
    d.EMP_POSITION_NAME,
    d.GRADE_NAME,
    d.ORGANIZATION_NAME,
    d.PROJECT,
    c.MOBILE,
    d.ASSIGNMENTS_DATE,
    d.PERMANENT_DATE,
    d.EXP_DATE,
    d.CON_TYP,
    d.HIRE_DATE,
    d.FIN_PROJECT,
    d.EGPC_EMAIL,
    central.get_emp_rotation(d.EMP_NUMBER, sysdate) AS Emp_Rotation
FROM central.emp_contact c
RIGHT JOIN central.xxapex_hr_emp_data d
ON c.EMP_ID = d.EMP_NUMBER;
