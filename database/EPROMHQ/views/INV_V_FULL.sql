
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "EPROMHQ"."INV_V_FULL" ("INV_ID", "DEPARTMENT_ID", "LOCATION_ID", "CATEGORY_ID", "COMPANY", "SERIAL", "EMPLOYEE_NAME", "EMPLOYEE_ID", "EMPLOYEE_DEPARTMENT", "RECEIVED_DATE", "PERCENTAGE", "PO_DETAILS", "REMARKS", "LAST_EXIST_DATE", "CREATED_AT", "UPDATED_AT", "PLACEMENT_DETAILS", "MODEL_ID", "CATEGORY_NAME", "CATEGORY_NAME_AR", "DEPARTMENT_NAME", "MODEL_NAME", "MODEL_NAME_AR", "LOCATION_NAME", "EMP_NAME", "EMP_PROJECT") AS
  SELECT
    INV."INV_ID",
    INV."DEPARTMENT_ID",
    INV."LOCATION_ID",
    INV."CATEGORY_ID",
    cp."COMPANY",
    INV."SERIAL",
    INV."EMPLOYEE_NAME",
    INV."EMPLOYEE_ID",
    INV."EMPLOYEE_DEPARTMENT",
    INV."RECEIVED_DATE",
    INV."PERCENTAGE",
    INV."PO_DETAILS",
    INV."REMARKS",
    INV."LAST_EXIST_DATE",
    INV."CREATED_AT",
    INV."UPDATED_AT",
    INV."PLACEMENT_DETAILS",
    INV."MODEL_ID",
    C.CATEGORY_NAME,
    C.CATEGORY_NAME_AR,
    D.DEPARTMENT_NAME,
    M.MODEL_NAME,
    M.MODEL_NAME_AR,
    L.LOCATION_NAME,
    E.EMP_NAME,
    E.PROJECT EMP_PROJECT
FROM
    INV_INVENTORIES INV
    LEFT JOIN INV_CATEGORIES  C ON INV.CATEGORY_ID = C.CATEGORY_ID
    LEFT JOIN INV_DEPARTMENTS D ON D.DEPARTMENT_ID = INV.DEPARTMENT_ID
    LEFT JOIN INV_ITEM_MODELS M ON M.MODEL_ID = INV.MODEL_ID
    LEFT JOIN INV_LOCATIONS   L ON L.LOCATION_ID = INV.LOCATION_ID
    LEFT JOIN INV_EMPS        E ON E.EMP_ID = INV.EMPLOYEE_ID
    left join COMPANY_LOOKUP cp on cp.COMPANY_id = inv.COMPANY_id;
