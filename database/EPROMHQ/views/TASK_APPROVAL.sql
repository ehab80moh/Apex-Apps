
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "EPROMHQ"."TASK_APPROVAL" ("USER_NAME", "REQUEST_ID", "REQUEST_NO", "IT_NOTE", "DESCRIPTION", "REQUEST_DATE", "REQUEST_TYPE", "STATUES", "EMP_ID", "MANAGER_ID") AS
  select REQ_USERS.USER_NAME as USER_NAME,
    REQ_REQUESTS.REQUEST_NO as REQUEST_NO,
    REQ_REQUESTS.REQUEST_ID as REQUEST_ID,
    REQ_REQUESTS.IT_NOTE as IT_NOTE,
    REQ_REQUESTS.DESCRIPTION as DESCRIPTION,
    REQ_REQUESTS.REQUEST_DATE as REQUEST_DATE,
    REQ_REQUESTS.REQUEST_TYPE as REQUEST_TYPE,
    REQ_REQUESTS.STATUES as STATUES,
    REQ_USERS.EMP_ID as EMP_ID,
    GET_MANAGER(REQ_USERS.EMP_ID)  as Manager
 from REQ_USERS REQ_USERS,
    REQ_REQUESTS REQ_REQUESTS
 where REQ_USERS.EMP_ID=REQ_REQUESTS.EMP_ID;
