
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "EPROMHQ"."VAC_EMP_BENEFITS_WEIGHT_V" ("EMP_ID", "WEIGHT", "TRIP_ID", "TRIP_NAME", "TRIP_YEAR", "TRIP_TYPE", "APPLICATION_START_DATE", "APPLICATION_END_DATE", "UNIT_LIMITS") AS
  select b.emp_id,w."WEIGHT",w."TRIP_ID",w."TRIP_NAME",w."TRIP_YEAR",w."TRIP_TYPE",w."APPLICATION_START_DATE",w."APPLICATION_END_DATE",w."UNIT_LIMITS" from vac_trip_weight_v w join vac_prev_benefits b
on w.trip_id = b.trip_id;
