
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "EPROMHQ"."VAC_SUMMER_WISHES_V" ("WISH_ID", "BLOC_ID", "ORD", "EMP_ID", "TRIP_ID", "NEED_TRANSPORTATION", "EMP_LAST_BENEFIT", "EMP_MOBILE", "EMP_WHATS", "CREATED_BY", "SUMMER_APPLICATION_ID", "APPLICATION_STATUS", "CREATED_AT") AS
  SELECT
    w.WISH_ID,
    w.BLOC_ID,
    w.ORD,
    a.EMP_ID,
    a.TRIP_ID,
    a.NEED_TRANSPORTATION,

    -- أحدث HISTORY من VAC_HISTORY أو "لايوجد" لو NULL
    NVL((
        SELECT h2.HISTORY
        FROM (
            SELECT h.HISTORY
            FROM VAC_HISTORY h
            WHERE h.EMP_ID = a.EMP_ID
            ORDER BY h.ID DESC
        ) h2
        WHERE ROWNUM = 1
    ), 'لا يوجد استفادات مسبقة') AS EMP_LAST_BENEFIT,

    a.EMP_MOBILE,
    a.EMP_WHATS,
    a.CREATED_BY,
    a.SUMMER_APPLICATION_ID,
    a.APPLICATION_STATUS,
    a.CREATED_AT

FROM
    VAC_SUMMER_APPLICATIONS a
JOIN
    VAC_EMP_WISHES w
    ON a.TRIP_ID = w.TRIP_ID AND a.EMP_ID = w.EMP_ID;
