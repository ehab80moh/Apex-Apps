
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "EPROMHQ"."VAC_TRIP_BLOCS_V" ("LOCATION_ID", "LOCATION_NAME", "CITY_ID", "CITY_NAME", "UNIT_ID", "UNIT_NAME", "UNIT_DESC", "BLOC_ID", "DATE_FROM", "DATE_TO", "BLOC_PRICE", "M_9", "M_10", "TRIP_ID", "TRIP_NAME", "TRIP_YEAR", "TRIP_TYPE", "APPLICATION_START_DATE", "APPLICATION_END_DATE") AS
  SELECT
  VAC_LOCATIONS.LOCATION_ID,
  VAC_LOCATIONS.LOCATION_NAME,
  VAC_LOCATIONS.city_NAME city_id,
  vac_cities.city_name,
  VAC_UNITS.UNIT_ID,
  VAC_UNITS.UNIT_NAME,
  VAC_UNITS.UNIT_DESC,
  VAC_BLOCS.BLOC_ID,
  VAC_BLOCS.DATE_FROM,
  VAC_BLOCS.DATE_TO,
  VAC_BLOCS.BLOC_PRICE,
  VAC_BLOCS.M_9,
  VAC_BLOCS.M_10,
  VAC_TRIPS.TRIP_ID,
  VAC_TRIPS.TRIP_NAME,
  VAC_TRIPS.TRIP_YEAR,
  VAC_TRIPS.TRIP_TYPE,
  VAC_TRIPS.APPLICATION_START_DATE,
  VAC_TRIPS.APPLICATION_END_DATE
FROM
  VAC_LOCATIONS
  INNER JOIN VAC_UNITS ON VAC_LOCATIONS.LOCATION_ID = VAC_UNITS.LOCATION_ID
  INNER JOIN VAC_BLOCS ON VAC_UNITS.UNIT_ID = VAC_BLOCS.UNIT_ID
  INNER JOIN VAC_TRIPS ON VAC_TRIPS.TRIP_ID = VAC_LOCATIONS.TRIP_ID
  INNER JOIN vac_cities ON vac_cities.city_id = VAC_LOCATIONS.city_NAME;
