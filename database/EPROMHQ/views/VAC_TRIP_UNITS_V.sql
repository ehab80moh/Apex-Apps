
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "EPROMHQ"."VAC_TRIP_UNITS_V" ("LOCATION_ID", "LOCATION_NAME", "CITY_NAME", "UNIT_ID", "UNIT_NAME", "UNIT_DESC", "TRIP_ID", "TRIP_NAME", "TRIP_YEAR", "TRIP_TYPE", "APPLICATION_START_DATE", "APPLICATION_END_DATE", "IMAGES", "THUMBS", "UNIT_INSTRUCTIONS", "UNIT_YOUTUBE", "UNIT_LOCATION", "UNIT_IMAGES") AS
  Select
  VAC_LOCATIONS.LOCATION_ID,
  VAC_LOCATIONS.LOCATION_NAME,
  VAC_LOCATIONS.CITY_NAME,
  VAC_UNITS.UNIT_ID,
  VAC_UNITS.UNIT_NAME,
  VAC_UNITS.UNIT_DESC,
  VAC_TRIPS."TRIP_ID",VAC_TRIPS."TRIP_NAME",VAC_TRIPS."TRIP_YEAR",VAC_TRIPS."TRIP_TYPE",VAC_TRIPS."APPLICATION_START_DATE",VAC_TRIPS."APPLICATION_END_DATE"
  ,m.images,m.thumbs
  ,VAC_UNITS.unit_instructions
  ,VAC_UNITS.UNIT_YOUTUBE
,VAC_UNITS.UNIT_LOCATION
,VAC_UNITS.UNIT_IMAGES
From
       VAC_UNITS
  Inner Join VAC_LOCATIONS On VAC_LOCATIONS.LOCATION_ID = VAC_UNITS.LOCATION_ID
  Inner Join VAC_TRIPS On VAC_TRIPS.TRIP_ID = VAC_LOCATIONS.TRIP_ID
  left join vac_units_media_agg m on m.unit_id = VAC_UNITS.UNIT_ID;
