
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "EPROMHQ"."VAC_WINTER_APP_Estb3ad_VIEW" ("EMP_ID", "EMP_NAME", "TRIP_ID", "MOBILE", "WINTER_APP_ID", "APPLICATION_STATUS", "CREATED_AT", "NATIONAL_IDENTIFIER", "EMP_DATE_OF_BIRTH", "EMP_POSITION_NAME", "SITE_CODE", "ORGANIZATION_NAME", "GRADE_NAME", "EXCEL_POS", "PROJECT", "COMP_EMAIL", "PAY_EMAIL", "EGPC_EMAIL", "MAR_STAT", "JOB_DATE", "PRIM_ADDRESS", "FIN_PROJECT", "CON_TYP", "HIRE_DATE", "MAIN_DEPARTMENT", "ALL_BENEFITS", "EXP_IN_2025", "AGE_IN_2025") AS
  SELECT
    A.EMP_ID,
    E.EMP_NAME,
    A.TRIP_ID,
    c.MOBILE,
    A.WINTER_APP_ID,
    A.APPLICATION_STATUS,
    TO_CHAR(A.CREATED_AT, 'YYYY-MM-DD') AS CREATED_AT, -- تحويل التاريخ لنص
    E.NATIONAL_IDENTIFIER,
    E.EMP_DATE_OF_BIRTH,
    E.EMP_POSITION_NAME,
    E.SITE_CODE,
    E.ORGANIZATION_NAME,
    E.CURRENT_GRADE as GRADE_NAME,
    E.EXCEL_POS,
    E.PROJECT,
    E.COMP_EMAIL,
    E.PAY_EMAIL,
    E.EGPC_EMAIL,
    E.MAR_STAT,
    E.JOB_DATE,
    E.PRIM_ADDRESS,
    E.FIN_PROJECT,
    E.CON_TYP,
    E.HIRE_DATE,
    E.MAIN_DEPARTMENT,
    H.ALL_BENEFITS,
    -- حساب الخبرة في سنة 2025
    CASE
        WHEN REGEXP_LIKE(E.HIRE_DATE, '^\d{4}-\d{2}-\d{2}$') THEN
            2025 - EXTRACT(YEAR FROM TO_DATE(E.HIRE_DATE, 'YYYY-MM-DD'))
        WHEN REGEXP_LIKE(E.HIRE_DATE, '^\d{2}/\d{2}/\d{4}$') THEN
            2025 - EXTRACT(YEAR FROM TO_DATE(E.HIRE_DATE, 'DD/MM/YYYY'))
        ELSE
            NULL
    END AS EXP_IN_2025,
    -- حساب العمر في سنة 2025
    CASE
        WHEN REGEXP_LIKE(E.EMP_DATE_OF_BIRTH, '^\d{4}-\d{2}-\d{2}$') THEN
            2025 - EXTRACT(YEAR FROM TO_DATE(E.EMP_DATE_OF_BIRTH, 'YYYY-MM-DD'))
        WHEN REGEXP_LIKE(E.EMP_DATE_OF_BIRTH, '^\d{2}/\d{2}/\d{4}$') THEN
            2025 - EXTRACT(YEAR FROM TO_DATE(E.EMP_DATE_OF_BIRTH, 'DD/MM/YYYY'))
        ELSE
            NULL
    END AS AGE_IN_2025
FROM EPROMHQ.VAC_WINTER_APPLICATIONS A
LEFT JOIN CENTRAL.XXAPEX_HR_EMP_DATA E
    ON A.EMP_ID = E.EMP_NUMBER
LEFT JOIN EPROMHQ.VAC_HISTORY_VIEW H
    ON A.EMP_ID = H.EMP_ID
    left join central.EMP_CONTACT c
        ON c.EMP_ID = a.EMP_ID

WHERE A.APPLICATION_STATUS = 'N';
