
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "EPROMHQ"."VIEW_CASE_DETAILS" ("CASE_ID", "CASE_ACTUAL_NUMBER", "CASE_START_DATE", "CASE_END_DATE", "CASE_STATUS", "CASE_TYPE", "CASE_TYPE_ID", "PARTY_TYPE_ID", "PARTY_NAME", "PARTY_ADDRESS", "PARTY_NATIONAL_ID", "PARTY_PHONE", "PARTY_TYPE", "PARTY_CATEGORY", "EMP_ID", "HEARING_ID", "HEARING_START_DATE", "HEARING_END_DATE", "HEARING_COURT", "HEARING_NUMBER", "LAWYER_NAME", "ATTACHMENT_ID", "ATTACHMENT_NAME", "ATTACHMENT_FILE_NAME", "SMS_EMP_ID", "SMS_7_DAYS", "SMS_3_DAYS", "SMS_1_DAY", "SMS_TEXT", "EMP_NUMBER_FROM_EMP_DATA", "EMP_NAME_FROM_EMP_DATA", "EMP_NUMBER_FROM_EXEMP_DATA", "EMP_NAME_FROM_EXEMP_DATA") AS
  SELECT
    C.CASE_ID,
    C.CASE_ACTUAL_NUMBER,
    C.START_DATE AS CASE_START_DATE,
    C.END_DATE AS CASE_END_DATE,
    C.STATUS AS CASE_STATUS,
    CT.TYPE AS CASE_TYPE,
    CT.ID AS CASE_TYPE_ID,
    P.PARTY_TYPE_ID,
    P.NAME AS PARTY_NAME,
    P.ADRESS AS PARTY_ADDRESS,
    P.NATIONAL_ID AS PARTY_NATIONAL_ID,
    P.PHONE_NUMBER AS PARTY_PHONE,
    P.EXTERNAL_INTERNAL AS PARTY_TYPE,
    PT.TYPE AS PARTY_CATEGORY,
    P.EMP_ID,
    L.HEARING_ID,
    L.START_DATE AS HEARING_START_DATE,
    L.END_DATE AS HEARING_END_DATE,
    L.COURT AS HEARING_COURT,
    L.HEARING_NUMBER,
    L.LAWYER_NAME,
    A.ATTACH_ID AS ATTACHMENT_ID,
    A.ATTACH_NAME AS ATTACHMENT_NAME,
    A.FILE_NAME AS ATTACHMENT_FILE_NAME,
    LS.EMP_ID AS SMS_EMP_ID,
    LS.SMS_7_DAYS,
    LS.SMS_3_DAYS,
    LS.SMS_1_DAY,
    LS.SMS_TEXT,
    HR_EMP.EMP_NUMBER AS EMP_NUMBER_FROM_EMP_DATA,
    HR_EMP.EMP_NAME AS EMP_NAME_FROM_EMP_DATA,
    HR_EXEMP.EMPLOYEE_NUMBER AS EMP_NUMBER_FROM_EXEMP_DATA,
    HR_EXEMP.EMPLOYEE_NAME AS EMP_NAME_FROM_EXEMP_DATA
FROM
    EPROMHQ.LAGD_CASES C
LEFT JOIN EPROMHQ.LAGD_CASES_TYPE CT ON C.CASES_TYPE_ID = CT.ID
LEFT JOIN EPROMHQ.LAGD_CASE_PARTIES CP ON C.CASE_ID = CP.CASEID
LEFT JOIN EPROMHQ.LAGD_PARTIES P ON CP.PARTYID = P.PARTY_ID
LEFT JOIN EPROMHQ.LAGD_PARTIES_TYPE PT ON CP.PARTYTYPEID = PT.ID
LEFT JOIN EPROMHQ.LAGD_HEARING L ON C.CASE_ID = L.CASE_ID
LEFT JOIN EPROMHQ.LAGD_ATTACHMENT A ON L.HEARING_ID = A.SOURCE_ID
LEFT JOIN EPROMHQ.LAGD_LOG_SMS LS ON LS.CASE_ID = C.CASE_ID
LEFT JOIN CENTRAL.XXAPEX_HR_EMP_DATA HR_EMP
    ON HR_EMP.EMP_NUMBER = P.EMP_ID
    OR HR_EMP.EMP_NUMBER = LS.EMP_ID
LEFT JOIN CENTRAL.XXAPEX_HR_EXEMP_DATA HR_EXEMP
    ON HR_EXEMP.EMPLOYEE_NUMBER = P.EMP_ID
    OR HR_EXEMP.EMPLOYEE_NUMBER = LS.EMP_ID;
