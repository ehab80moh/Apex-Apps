
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "EPROMHQ"."VW_DISTINCT_PROJECTS" ("PROJECT_ID", "PROJECT_NAME") AS
  SELECT
    ROW_NUMBER() OVER (ORDER BY PROJECT) AS PROJECT_ID,
    TRIM(PROJECT) AS PROJECT_NAME
FROM (
    SELECT DISTINCT PROJECT
    FROM central.XXAPEX_HR_EMP_DATA
    WHERE PROJECT IS NOT NULL
);
