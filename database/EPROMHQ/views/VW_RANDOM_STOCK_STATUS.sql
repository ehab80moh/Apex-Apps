
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "EPROMHQ"."VW_RANDOM_STOCK_STATUS" ("MODEL_ID", "MODEL_NAME", "COMPANY_NAME", "TOTAL_ADDED", "TOTAL_DEDUCTED", "AVAILABLE", "IS_ACTIVE") AS
  SELECT
  m.MODEL_ID,
  m.MODEL_NAME,
  m.COMPANY_NAME,

  -- إجمالي المضاف
  (SELECT SUM(a.QUANTITY)
   FROM EPROMHQ.INV_RANDOM_ADDITION a
   WHERE a.MODEL_ID = m.MODEL_ID) AS TOTAL_ADDED,

  -- إجمالي المصروف
  (SELECT COUNT(*)
   FROM EPROMHQ.INV_RANDOM_DEDUCTED d
   WHERE d.MODEL_ID = m.MODEL_ID) AS TOTAL_DEDUCTED,

  -- الرصيد الحالي
  (SELECT AVAILABLE_LEVEL
   FROM EPROMHQ.INV_RANDOM_LEVEL l
   WHERE l.MODEL_ID = m.MODEL_ID) AS AVAILABLE,

  m.IS_ACTIVE

FROM EPROMHQ.INV_RANDOM_MODELS m;
